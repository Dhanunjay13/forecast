# FEATURE ENGINEERING
# ============================================================

def create_features(history):

    current_time = (
        history["Datetime"].iloc[-1]
        + timedelta(hours=1)
    )

    row = {}

    # --------------------------------------------------------
    # Calendar variables
    # --------------------------------------------------------

    row["Hour"] = current_time.hour

    row["Day"] = current_time.day

    row["DayOfWeek"] = current_time.dayofweek

    row["Month"] = current_time.month

    row["Year"] = current_time.year

    row["IsWeekend"] = int(
        current_time.dayofweek in [5, 6]
    )

    row["IsHoliday"] = int(
        current_time.date() in holiday_dates
    )


    # --------------------------------------------------------
    # Lag variables
    # --------------------------------------------------------

    row["lag_1"] = (
        history["PJMW_MW"].iloc[-1]
    )

    row["lag_2"] = (
        history["PJMW_MW"].iloc[-2]
    )

    row["lag_3"] = (
        history["PJMW_MW"].iloc[-3]
    )

    row["lag_24"] = (
        history["PJMW_MW"].iloc[-24]
    )

    row["lag_48"] = (
        history["PJMW_MW"].iloc[-48]
    )

    row["lag_168"] = (
        history["PJMW_MW"].iloc[-168]
    )


    # --------------------------------------------------------
    # Rolling statistics
    # --------------------------------------------------------

    row["rolling_mean_24"] = (
        history["PJMW_MW"]
        .iloc[-24:]
        .mean()
    )

    row["rolling_mean_168"] = (
        history["PJMW_MW"]
        .iloc[-168:]
        .mean()
    )

    row["rolling_std_24"] = (
        history["PJMW_MW"]
        .iloc[-24:]
        .std()
    )


    return (
        pd.DataFrame([row]),
        current_time
    )


# ============================================================
# FORECAST FUNCTION
# ============================================================

def generate_forecast(
    historical_df,
    number_of_days
):

    history = historical_df[
        [
            "Datetime",
            "PJMW_MW"
        ]
    ].copy()

    predictions = []

    total_hours = (
        number_of_days * 24
    )


    for _ in range(total_hours):

        X_future, timestamp = (
            create_features(history)
        )


        # ----------------------------------------------------
        # Check expected columns
        # ----------------------------------------------------

        missing_columns = [
            col
            for col in feature_cols
            if col not in X_future.columns
        ]


        if missing_columns:

            raise ValueError(
                "Missing model features: "
                + str(missing_columns)
            )


        # ----------------------------------------------------
        # XGBoost prediction
        # ----------------------------------------------------

        prediction = model.predict(
            X_future[
                feature_cols
            ]
        )[0]


        # ----------------------------------------------------
        # Prevent impossible negative demand
        # ----------------------------------------------------

        prediction = max(
            0,
            float(prediction)
        )


        predictions.append(
            {
                "Datetime": timestamp,
                "Forecast_MW": prediction
            }
        )


        # ----------------------------------------------------
        # Add prediction to history
        # ----------------------------------------------------

        new_row = pd.DataFrame(
            {
                "Datetime": [
                    timestamp
                ],

                "PJMW_MW": [
                    prediction
                ]
            }
        )


        history = pd.concat(
            [
                history,
                new_row
            ],
            ignore_index=True
        )


    return pd.DataFrame(
        predictions
    )


