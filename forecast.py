@st.cache_data
def load_data():

    df = pd.read_excel(
        "PJMW_MW_Hourly.xlsx"
    )

    # --------------------------------------------------------
    # Rename column if necessary
    # --------------------------------------------------------

    if "Datetime" not in df.columns:

        possible_date_columns = [
            col for col in df.columns
            if "date" in col.lower()
            or "time" in col.lower()
        ]

        if possible_date_columns:

            df = df.rename(
                columns={
                    possible_date_columns[0]: "Datetime"
                }
            )

        else:

            raise ValueError(
                "Datetime column not found in dataset."
            )


    # --------------------------------------------------------
    # Target column
    # --------------------------------------------------------

    if "PJMW_MW" not in df.columns:

        possible_target_columns = [
            col for col in df.columns
            if "PJMW" in col.upper()
            or "MW" in col.upper()
        ]

        if possible_target_columns:

            df = df.rename(
                columns={
                    possible_target_columns[0]: "PJMW_MW"
                }
            )

        else:

            raise ValueError(
                "PJMW_MW target column not found."
            )


    df["Datetime"] = pd.to_datetime(
        df["Datetime"],
        errors="coerce"
    )

    df["PJMW_MW"] = pd.to_numeric(
        df["PJMW_MW"],
        errors="coerce"
    )

    df = df.dropna(
        subset=[
            "Datetime",
            "PJMW_MW"
        ]
    )

    df = (
        df
        .sort_values("Datetime")
        .reset_index(drop=True)
    )

    return df


